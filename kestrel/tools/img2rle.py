#!/usr/bin/env python3
"""img2rle.py IMAGE NAME OUT.c -- an image as a palette + run-length C array.

Lossless: every pixel keeps its exact RGB value. The palette holds up to
256 colours; the pixel stream (row by row) is a list of runs, each
(palette index, length - 1) with runs at most 256 pixels long, so the
array is uint8_t pairs. The result is decoded again and compared before
anything is written. Kernel side: include/kernel/image.h."""
import sys
from collections import Counter
from PIL import Image

def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    path, name, out = sys.argv[1:]
    im = Image.open(path).convert('RGB')
    w, h = im.size
    raw = im.tobytes()
    px = [tuple(raw[k:k + 3]) for k in range(0, len(raw), 3)]
    counts = Counter(px)
    if len(counts) > 256:
        sys.exit('img2rle: more than 256 colours; this format is for flat artwork')
    palette = sorted(counts, key=lambda c: (-counts[c], c))   # [0]: the most common, the background
    index = {c: i for i, c in enumerate(palette)}
    runs = []
    i = 0
    while i < len(px):
        c, n = px[i], 1
        while i + n < len(px) and px[i + n] == c and n < 256:
            n += 1
        runs.append((index[c], n - 1))
        i += n
    # round trip
    back = []
    for ci, n1 in runs:
        back.extend([palette[ci]] * (n1 + 1))
    assert back == px, 'img2rle: round trip failed'
    with open(out, 'w') as f:
        f.write(f'/* {out} -- generated by tools/img2rle.py from {path}; do not edit.\n')
        f.write(f' * {w}x{h}, {len(palette)} colours, {len(runs)} runs (lossless). */\n')
        f.write('#include <kernel/image.h>\n\n')
        f.write(f'static const uint32_t {name}_palette[{len(palette)}] = {{\n')
        for k in range(0, len(palette), 6):
            f.write('    ' + ', '.join('0x%06X' % ((r << 16) | (g << 8) | b) for r, g, b in palette[k:k + 6]) + ',\n')
        f.write('};\n\n')
        f.write(f'static const uint8_t {name}_runs[{2 * len(runs)}] = {{\n')
        flat = [v for run in runs for v in run]
        for k in range(0, len(flat), 16):
            f.write('    ' + ', '.join(str(v) for v in flat[k:k + 16]) + ',\n')
        f.write('};\n\n')
        f.write(f'const struct rle_image {name} = {{ {w}, {h}, {len(palette)}, {len(runs)}, {name}_palette, {name}_runs }};\n')
    print(f'img2rle: {path}: {w}x{h}, {len(palette)} colours, {len(runs)} runs -> {out}')

main()
